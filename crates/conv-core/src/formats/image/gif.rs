//! GIF decode and encode — 8-bit palette only (which is all GIF ever is), first frame only for
//! multi-image/animated files, matching this crate's "one image in, one image out" model — the
//! same scope line `ico.rs`'s "largest entry, no cross-entry fallback" precedent draws.
//!
//! Unlike PNG/WebP, GIF's compression is **LZW** (Lempel-Ziv-Welch): a dictionary-of-byte-
//! sequences scheme with no Huffman coding at all, documented and unchanged since the GIF87a/89a
//! specs. The one detail this module validated empirically rather than trusting memory for: the
//! exact point at which the LZW code width grows. Some descriptions of LZW-family formats call
//! for an "early change" — growing the code width one dictionary slot sooner than the textbook
//! algorithm would. Cross-checked against Pillow decoding real files (including one hitting the
//! full 9-to-12-bit code-width range and a mid-stream dictionary-full reset): real GIF encoders
//! use the **textbook** timing (grow when the dictionary needs `2^width` entries, not
//! `2^width - 1`), not "early change" — see [`lzw_decode`]'s tests.
//!
//! [`encode`] requires the image to already have at most 256 distinct colors (counting
//! transparency as one more, if used) — GIF is fundamentally a palette format, and building a
//! real color quantizer to downsample an arbitrary photo to 256 colors is separate, later work,
//! an honest scope line rather than an oversight (see [`encode`]'s own docs).

use super::raster::{checked_rgba_len, RawImage};
use crate::{ConvertError, ConvertOptions, Format};
use std::collections::HashMap;

fn malformed() -> ConvertError {
    ConvertError::MalformedInput {
        format: Format::Gif,
    }
}

fn unsupported(feature: &'static str) -> ConvertError {
    ConvertError::UnsupportedFeature {
        format: Format::Gif,
        feature,
    }
}

const HEADER_LEN: usize = 6; // "GIF87a" or "GIF89a"
const LSD_LEN: usize = 7; // width(2) + height(2) + packed(1) + bg(1) + aspect(1)

const EXTENSION_INTRODUCER: u8 = 0x21;
const GRAPHIC_CONTROL_LABEL: u8 = 0xf9;
const IMAGE_SEPARATOR: u8 = 0x2c;
const TRAILER: u8 = 0x3b;

/// Least-significant-bit-first bit reader, same packing convention as `zlib.rs`'s stored blocks
/// and `vp8l.rs`'s whole bitstream — GIF's LZW codes are packed the same way, so a code is just
/// `read_bits(code_width)` with the first-read bit landing in the low end of the result.
struct BitReader<'a> {
    data: &'a [u8],
    pos: usize,
}

impl<'a> BitReader<'a> {
    fn new(data: &'a [u8]) -> Self {
        BitReader { data, pos: 0 }
    }

    fn read_bits(&mut self, n: u32) -> Option<u32> {
        let mut v = 0u32;
        for i in 0..n {
            let byte_idx = self.pos / 8;
            if byte_idx >= self.data.len() {
                return None;
            }
            let bit = (self.data[byte_idx] >> (self.pos % 8)) & 1;
            v |= u32::from(bit) << i;
            self.pos += 1;
        }
        Some(v)
    }
}

struct BitWriter {
    out: Vec<u8>,
    cur: u8,
    nbits: u32,
}

impl BitWriter {
    fn new() -> Self {
        BitWriter {
            out: Vec::new(),
            cur: 0,
            nbits: 0,
        }
    }

    fn write_bits(&mut self, value: u32, n: u32) {
        for i in 0..n {
            let bit = ((value >> i) & 1) as u8;
            self.cur |= bit << self.nbits;
            self.nbits += 1;
            if self.nbits == 8 {
                self.out.push(self.cur);
                self.cur = 0;
                self.nbits = 0;
            }
        }
    }

    fn finish(mut self) -> Vec<u8> {
        if self.nbits > 0 {
            self.out.push(self.cur);
        }
        self.out
    }
}

/// A code can never legally reference a dictionary slot beyond this — the format's own 12-bit
/// code-width ceiling.
const MAX_DICT_SIZE: usize = 4096;

fn fresh_table(clear_code: usize) -> Vec<Vec<u8>> {
    let mut table: Vec<Vec<u8>> = (0..clear_code).map(|i| vec![i as u8]).collect();
    table.push(Vec::new()); // clear_code's slot — never read; that code is special-cased
    table.push(Vec::new()); // end_code's slot — likewise
    table
}

/// Decodes GIF's LZW-compressed image data into a flat array of palette indices, bounded to
/// exactly `expected_len` bytes — already known from the image's own declared width/height,
/// validated against this crate's pixel-count ceiling before this is ever called, the same
/// decompression-bomb defense `zlib.rs`/`vp8l.rs` apply to their own compressed streams.
fn lzw_decode(data: &[u8], min_code_size: u8, expected_len: usize) -> Option<Vec<u8>> {
    if !(2..=8).contains(&min_code_size) {
        return None;
    }
    let clear_code = 1usize << min_code_size;
    let end_code = clear_code + 1;

    let mut reader = BitReader::new(data);
    let mut table = fresh_table(clear_code);
    let mut next_code = table.len();
    let mut code_width = u32::from(min_code_size) + 1;
    let mut output = Vec::with_capacity(expected_len);
    let mut prev: Option<Vec<u8>> = None;

    loop {
        let code = reader.read_bits(code_width)? as usize;
        if code == clear_code {
            table = fresh_table(clear_code);
            next_code = table.len();
            code_width = u32::from(min_code_size) + 1;
            prev = None;
            continue;
        }
        if code == end_code {
            break;
        }

        let entry: Vec<u8> = if code < table.len() {
            table[code].clone()
        } else if code == next_code {
            // KwKwK: the one case where the code being read is the entry about to be *added*.
            let p = prev.as_ref()?;
            let mut e = p.clone();
            e.push(p[0]);
            e
        } else {
            return None;
        };

        if output.len() + entry.len() > expected_len {
            return None;
        }
        output.extend_from_slice(&entry);

        if let Some(p) = &prev {
            if next_code < MAX_DICT_SIZE {
                let mut new_entry = p.clone();
                new_entry.push(entry[0]);
                table.push(new_entry);
                next_code += 1;
                if next_code == (1usize << code_width) && code_width < 12 {
                    code_width += 1;
                }
            }
        }
        prev = Some(entry);
    }

    if output.len() != expected_len {
        return None;
    }
    Some(output)
}

/// Encodes palette indices as GIF's LZW format — the standard textbook algorithm (greedy
/// longest-dictionary-match), same growth timing [`lzw_decode`]'s tests validated. Resets the
/// dictionary with an extra Clear code if it fills up mid-stream, rather than capping compression
/// there — a real (if simply-implemented, not exhaustively-searched) compressor, since GIF has no
/// "stored block" escape hatch the way DEFLATE does for a minimal encoder to lean on.
fn lzw_encode(indices: &[u8], min_code_size: u8) -> Vec<u8> {
    let clear_code = 1u32 << min_code_size;
    let end_code = clear_code + 1;
    let mut code_width = u32::from(min_code_size) + 1;

    let mut writer = BitWriter::new();
    writer.write_bits(clear_code, code_width);

    let mut dict: HashMap<Vec<u8>, u32> = HashMap::new();
    let mut next_code = end_code + 1;
    let mut w: Vec<u8> = Vec::new();

    let code_for = |w: &[u8], dict: &HashMap<Vec<u8>, u32>| -> u32 {
        if w.len() == 1 {
            u32::from(w[0])
        } else {
            dict[w]
        }
    };

    for &c in indices {
        let mut candidate = w.clone();
        candidate.push(c);
        let known = candidate.len() == 1 || dict.contains_key(&candidate);
        if known {
            w = candidate;
            continue;
        }

        writer.write_bits(code_for(&w, &dict), code_width);

        if next_code >= MAX_DICT_SIZE as u32 {
            writer.write_bits(clear_code, code_width);
            dict.clear();
            next_code = end_code + 1;
            code_width = u32::from(min_code_size) + 1;
        } else {
            dict.insert(candidate, next_code);
            next_code += 1;
            // Deliberately `+ 1` relative to `lzw_decode`'s own `next_code == 2^width` check:
            // the decoder can never insert a dictionary entry while decoding its *first* code
            // (there's no previous symbol yet to combine with), so its `next_code` is always
            // exactly one entry behind this encoder's at the equivalent point in the stream.
            // Growing the width here at the same nominal threshold the decoder uses would grow
            // one code too early and desync the two — confirmed by round-tripping this encoder's
            // output back through `lzw_decode` during development, not just reasoned out.
            if next_code == (1 << code_width) + 1 && code_width < 12 {
                code_width += 1;
            }
        }
        w = vec![c];
    }
    if !w.is_empty() {
        writer.write_bits(code_for(&w, &dict), code_width);
    }
    writer.write_bits(end_code, code_width);
    writer.finish()
}

fn read_u16_le(input: &[u8], offset: usize) -> Option<u16> {
    let bytes = input.get(offset..offset + 2)?;
    Some(u16::from_le_bytes([bytes[0], bytes[1]]))
}

/// Skips a generic (non-Graphic-Control) extension block: a label byte, already consumed by the
/// caller, followed by size-prefixed sub-blocks up to a zero-length terminator.
fn skip_sub_blocks(input: &[u8], pos: &mut usize) -> Result<(), ConvertError> {
    loop {
        let size = *input.get(*pos).ok_or_else(malformed)? as usize;
        *pos += 1;
        if size == 0 {
            return Ok(());
        }
        if *pos + size > input.len() {
            return Err(malformed());
        }
        *pos += size;
    }
}

fn read_sub_blocks(input: &[u8], pos: &mut usize) -> Result<Vec<u8>, ConvertError> {
    let mut out = Vec::new();
    loop {
        let size = *input.get(*pos).ok_or_else(malformed)? as usize;
        *pos += 1;
        if size == 0 {
            return Ok(out);
        }
        let chunk = input.get(*pos..*pos + size).ok_or_else(malformed)?;
        out.extend_from_slice(chunk);
        *pos += size;
    }
}

/// Un-does GIF's row interlacing (4 passes: every 8th row from 0, every 8th from 4, every 4th
/// from 2, every 2nd from 1) — `flat` is the LZW output in that pass order; returns it reordered
/// to simple top-to-bottom row order.
fn deinterlace(flat: &[u8], width: usize, height: usize) -> Vec<u8> {
    let mut out = vec![0u8; flat.len()];
    const PASSES: [(usize, usize); 4] = [(0, 8), (4, 8), (2, 4), (1, 2)];
    let mut src_row = 0usize;
    for &(start, step) in &PASSES {
        let mut row = start;
        while row < height {
            let src = src_row * width;
            let dst = row * width;
            out[dst..dst + width].copy_from_slice(&flat[src..src + width]);
            src_row += 1;
            row += step;
        }
    }
    out
}

/// Decodes the first frame of a GIF into a [`RawImage`].
pub fn decode(input: &[u8], options: &ConvertOptions) -> Result<RawImage, ConvertError> {
    if options.is_cancelled() {
        return Err(ConvertError::Cancelled);
    }

    if input.len() < HEADER_LEN + LSD_LEN || &input[0..3] != b"GIF" {
        return Err(malformed());
    }
    if &input[3..6] != b"87a" && &input[3..6] != b"89a" {
        return Err(unsupported("gif-unknown-version"));
    }

    let mut pos = HEADER_LEN;
    let screen_width = read_u16_le(input, pos).ok_or_else(malformed)? as usize;
    let screen_height = read_u16_le(input, pos + 2).ok_or_else(malformed)? as usize;
    let lsd_packed = input[pos + 4];
    pos += LSD_LEN;
    let _ = (screen_width, screen_height); // the image's own descriptor carries the real size

    let global_table = if lsd_packed & 0x80 != 0 {
        let size = 2usize << (lsd_packed & 0x07);
        let table = read_color_table(input, &mut pos, size)?;
        Some(table)
    } else {
        None
    };

    let mut transparent_index: Option<u8> = None;

    loop {
        let marker = *input.get(pos).ok_or_else(malformed)?;
        pos += 1;
        match marker {
            EXTENSION_INTRODUCER => {
                let label = *input.get(pos).ok_or_else(malformed)?;
                pos += 1;
                if label == GRAPHIC_CONTROL_LABEL {
                    let size = *input.get(pos).ok_or_else(malformed)? as usize;
                    if size != 4 {
                        return Err(malformed());
                    }
                    let block = input.get(pos + 1..pos + 1 + size).ok_or_else(malformed)?;
                    let gce_packed = block[0];
                    transparent_index = if gce_packed & 0x01 != 0 {
                        Some(block[3])
                    } else {
                        None
                    };
                    pos += 1 + size;
                    let terminator = *input.get(pos).ok_or_else(malformed)?;
                    if terminator != 0 {
                        return Err(malformed());
                    }
                    pos += 1;
                } else {
                    skip_sub_blocks(input, &mut pos)?;
                }
            }
            IMAGE_SEPARATOR => {
                let left = read_u16_le(input, pos).ok_or_else(malformed)? as usize;
                let top = read_u16_le(input, pos + 2).ok_or_else(malformed)? as usize;
                let width = read_u16_le(input, pos + 4).ok_or_else(malformed)? as usize;
                let height = read_u16_le(input, pos + 6).ok_or_else(malformed)? as usize;
                let img_packed = *input.get(pos + 8).ok_or_else(malformed)?;
                let _ = (left, top);
                pos += 9;

                let local_table = if img_packed & 0x80 != 0 {
                    let size = 2usize << (img_packed & 0x07);
                    Some(read_color_table(input, &mut pos, size)?)
                } else {
                    None
                };
                let table = local_table
                    .as_ref()
                    .or(global_table.as_ref())
                    .ok_or_else(malformed)?;

                let min_code_size = *input.get(pos).ok_or_else(malformed)?;
                pos += 1;
                let lzw_data = read_sub_blocks(input, &mut pos)?;

                let rgba_len = checked_rgba_len(width as u32, height as u32, Format::Gif)?;
                let pixel_count = width.checked_mul(height).ok_or_else(malformed)?;
                let indices =
                    lzw_decode(&lzw_data, min_code_size, pixel_count).ok_or_else(malformed)?;
                let indices = if img_packed & 0x40 != 0 {
                    deinterlace(&indices, width, height)
                } else {
                    indices
                };

                let mut rgba = vec![0u8; rgba_len as usize];
                for (i, &idx) in indices.iter().enumerate() {
                    let color = table.get(idx as usize).copied().ok_or_else(malformed)?;
                    let alpha = if transparent_index == Some(idx) {
                        0
                    } else {
                        255
                    };
                    rgba[i * 4] = color[0];
                    rgba[i * 4 + 1] = color[1];
                    rgba[i * 4 + 2] = color[2];
                    rgba[i * 4 + 3] = alpha;
                }

                options.report_progress(1.0);
                return RawImage::new(width as u32, height as u32, rgba, Format::Gif);
            }
            TRAILER => return Err(malformed()), // reached the end with no image at all
            _ => return Err(malformed()),
        }

        if options.is_cancelled() {
            return Err(ConvertError::Cancelled);
        }
    }
}

fn read_color_table(
    input: &[u8],
    pos: &mut usize,
    size: usize,
) -> Result<Vec<[u8; 3]>, ConvertError> {
    let bytes = input.get(*pos..*pos + size * 3).ok_or_else(malformed)?;
    *pos += size * 3;
    Ok(bytes.chunks_exact(3).map(|c| [c[0], c[1], c[2]]).collect())
}

/// Encodes a [`RawImage`] as a single-frame, non-interlaced GIF. Requires the image to already
/// have at most 256 distinct colors — pixels with alpha `< 128` are treated as transparent (GIF
/// only ever has 1-bit transparency, not real alpha blending, so this is the closest a
/// partially-transparent pixel can be represented) and collapsed to one reserved palette entry;
/// everything else contributes its RGB to the palette by exact value. An image needing more than
/// 256 distinct colors (or 255, if it also needs a transparent entry) is rejected as an honest
/// gap rather than silently degraded through a color quantizer this crate doesn't have yet.
pub fn encode(image: &RawImage, options: &ConvertOptions) -> Result<Vec<u8>, ConvertError> {
    if options.is_cancelled() {
        return Err(ConvertError::Cancelled);
    }

    let pixel_count = image.width as usize * image.height as usize;
    let mut palette: Vec<[u8; 3]> = Vec::new();
    let mut color_index: HashMap<[u8; 3], u8> = HashMap::new();
    let mut indices = Vec::with_capacity(pixel_count);
    let mut needs_transparency = false;
    let mut transparent_index = 0u8;

    for i in 0..pixel_count {
        let base = i * 4;
        let (r, g, b, a) = (
            image.pixels[base],
            image.pixels[base + 1],
            image.pixels[base + 2],
            image.pixels[base + 3],
        );
        if a < 128 {
            needs_transparency = true;
            indices.push(u8::MAX); // placeholder, fixed up once the transparent index is chosen
            continue;
        }
        let color = [r, g, b];
        let idx = if let Some(&idx) = color_index.get(&color) {
            idx
        } else {
            if palette.len() >= 256 {
                return Err(unsupported("gif-too-many-colors"));
            }
            let idx = palette.len() as u8;
            palette.push(color);
            color_index.insert(color, idx);
            idx
        };
        indices.push(idx);
    }

    if needs_transparency {
        if palette.len() >= 256 {
            return Err(unsupported("gif-too-many-colors"));
        }
        transparent_index = palette.len() as u8;
        palette.push([0, 0, 0]);
        for idx in &mut indices {
            if *idx == u8::MAX {
                *idx = transparent_index;
            }
        }
    }
    if palette.is_empty() {
        palette.push([0, 0, 0]); // a 0x0 or fully-transparent image still needs a 1-entry table
    }

    let color_bits = bits_for_palette(palette.len());
    let table_size = 1usize << color_bits;
    palette.resize(table_size, [0, 0, 0]);
    let min_code_size = color_bits.max(2) as u8;

    let mut out = Vec::new();
    out.extend_from_slice(b"GIF89a");
    out.extend_from_slice(&(image.width as u16).to_le_bytes());
    out.extend_from_slice(&(image.height as u16).to_le_bytes());
    out.push(0x80 | ((color_bits as u8).saturating_sub(1))); // global color table, no sort
    out.push(0); // background color index
    out.push(0); // pixel aspect ratio
    for c in &palette {
        out.extend_from_slice(c);
    }

    if needs_transparency {
        out.push(EXTENSION_INTRODUCER);
        out.push(GRAPHIC_CONTROL_LABEL);
        out.push(4);
        out.push(0x01); // transparent color flag set, disposal method 0
        out.extend_from_slice(&0u16.to_le_bytes()); // delay time
        out.push(transparent_index);
        out.push(0); // block terminator
    }

    out.push(IMAGE_SEPARATOR);
    out.extend_from_slice(&0u16.to_le_bytes()); // left
    out.extend_from_slice(&0u16.to_le_bytes()); // top
    out.extend_from_slice(&(image.width as u16).to_le_bytes());
    out.extend_from_slice(&(image.height as u16).to_le_bytes());
    out.push(0); // no local color table, not interlaced

    out.push(min_code_size);
    let compressed = lzw_encode(&indices, min_code_size);
    for chunk in compressed.chunks(255) {
        out.push(chunk.len() as u8);
        out.extend_from_slice(chunk);
    }
    out.push(0); // terminator sub-block

    out.push(TRAILER);

    options.report_progress(1.0);
    Ok(out)
}

fn bits_for_palette(size: usize) -> usize {
    let mut bits = 1;
    while (1usize << bits) < size {
        bits += 1;
    }
    bits.max(1)
}

