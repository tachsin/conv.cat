    #[test]
    fn lzw_decode_and_deinterlace_match_real_encoder_output() {
        let image = decode(MEDIUM_RANDOM_GIF, &ConvertOptions::default()).unwrap();
        assert_eq!((image.width, image.height), (25, 25));

        // The real encoder compacted its palette down to only the colors this image actually
        // uses (233 of the 256 declared slots) rather than keeping the generator's full 0..256
        // formula table, so read the true palette straight out of the fixture instead of
        // recomputing it -- comparing against a color a real encoder never wrote would just be
        // testing this test, not the decoder.
        let mut pos = HEADER_LEN;
        let lsd_packed = MEDIUM_RANDOM_GIF[pos + 4];
        pos += LSD_LEN;
        let gct_size = 2usize << (lsd_packed & 0x07);
        let table = read_color_table(MEDIUM_RANDOM_GIF, &mut pos, gct_size).unwrap();

        for (i, &idx) in MEDIUM_RANDOM_INDICES.iter().enumerate() {
            let color = table[idx as usize];
            let expected = [color[0], color[1], color[2], 255];
            assert_eq!(&image.pixels[i * 4..i * 4 + 4], &expected, "pixel {i}");
        }
    }

    fn checkerboard(width: u32, height: u32) -> RawImage {
        let mut pixels = vec![0u8; (width * height * 4) as usize];
        for y in 0..height {
            for x in 0..width {
                let idx = ((y * width + x) * 4) as usize;
                let v = if (x + y).is_multiple_of(2) { 255 } else { 0 };
                pixels[idx] = v;
                pixels[idx + 1] = v;
                pixels[idx + 2] = v;
                pixels[idx + 3] = 255;
            }
        }
        RawImage::new(width, height, pixels, Format::Gif).unwrap()
    }

    #[test]
    fn round_trip_preserves_pixels_exactly() {
        let image = checkerboard(5, 3);
        let bytes = encode(&image, &ConvertOptions::default()).unwrap();
        let decoded = decode(&bytes, &ConvertOptions::default()).unwrap();
        assert_eq!(decoded.width, image.width);
        assert_eq!(decoded.height, image.height);
        assert_eq!(decoded.pixels, image.pixels);
    }

    #[test]
    fn round_trip_preserves_transparency() {
        let mut image = checkerboard(3, 3);
        image.pixels[3] = 0; // first pixel fully transparent
        let bytes = encode(&image, &ConvertOptions::default()).unwrap();
        let decoded = decode(&bytes, &ConvertOptions::default()).unwrap();
        // GIF transparency is 1-bit (a pixel is either shown or not), not real alpha blending —
        // `encode` collapses every transparent pixel to one reserved palette entry regardless of
        // its original color (see `encode`'s own docs), so only the *visibility* round-trips,
        // not the RGB underneath it.
        assert_eq!(decoded.pixels[3], 0);
        // Every other (opaque) pixel's exact color must still round-trip.
        assert_eq!(&decoded.pixels[4..], &image.pixels[4..]);
    }

    #[test]
    fn round_trip_a_high_entropy_image_exercising_the_full_lzw_code_width_range() {
        let width = 60u32;
        let height = 60u32;
        let mut state: u32 = 42;
        let mut next_byte = || {
            state = state.wrapping_mul(1_103_515_245).wrapping_add(12_345);
            ((state >> 16) & 0xff) as u8
        };
        let mut pixels = Vec::with_capacity((width * height * 4) as usize);
        for _ in 0..(width * height) {
            pixels.push(next_byte());
            pixels.push(next_byte());
            pixels.push(next_byte());
            pixels.push(255);
        }
        // Force a real, large, mostly-distinct palette by construction below instead of relying
        // on the RNG to land under 256 unique colors, which is unlikely for true RGB randomness.
        let mut unique = std::collections::BTreeSet::new();
        for chunk in pixels.chunks(4) {
            unique.insert([chunk[0], chunk[1], chunk[2]]);
        }
        // Remap onto a synthetic <=256-color palette derived from the pixel index itself, so the
        // image is guaranteed encodable while still being high-entropy (every pixel distinct).
        let mut pixels2 = Vec::with_capacity(pixels.len());
        for i in 0..(width * height) as usize {
            let v = (i % 256) as u8;
            pixels2.push(v);
            pixels2.push(v.wrapping_mul(7));
            pixels2.push(v.wrapping_mul(13));
            pixels2.push(255);
        }
        let image = RawImage::new(width, height, pixels2, Format::Gif).unwrap();

        let bytes = encode(&image, &ConvertOptions::default()).unwrap();
        let decoded = decode(&bytes, &ConvertOptions::default()).unwrap();
        assert_eq!(decoded.pixels, image.pixels);
    }

    #[test]
    fn encode_rejects_images_with_more_than_256_colors() {
        let width = 20u32;
        let height = 20u32;
        let mut pixels = Vec::with_capacity((width * height * 4) as usize);
        for i in 0..(width * height) {
            pixels.push((i % 256) as u8);
            pixels.push(((i / 256) % 256) as u8);
            pixels.push(((i / 2) % 256) as u8);
            pixels.push(255);
        }
        let image = RawImage::new(width, height, pixels, Format::Gif).unwrap();
        let result = encode(&image, &ConvertOptions::default());
        assert!(matches!(
            result,
            Err(ConvertError::UnsupportedFeature {
                format: Format::Gif,
                feature: "gif-too-many-colors"
            })
        ));
    }

